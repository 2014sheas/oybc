// Board-integrity PR-1 (docs/BOARD_INTEGRITY.md) — `pickPrimaryBoard` (the
// internal board-resolution helper) must never surface a board through a
// TOMBSTONED placement, or a member row would show a "primary board" it's
// no longer actually placed on.
describe('primary-board resolution excludes tombstoned placements', () => {
  it('a member whose only placement is tombstoned resolves to no board (not the dead one)', () => {
    const source = toTask({
      id: 'src',
      title: 'Source',
      currentCount: 10,
      maxCount: null,
      sharedCounterId: null,
      baseline: null,
      isDeleted: false,
      isCounter: true,
    });
    const board = toBoard({ id: 'board-1', name: 'Board One', status: BoardStatus.ACTIVE, isDeleted: false });

    const groups = buildSharedCounterGroups({
      tasks: [source],
      boards: [board],
      boardTasks: [{ taskId: 'src', boardId: 'board-1', isDeleted: true }].map(toBoardTask),
    });

    expect(groups).toHaveLength(1);
    expect(groups[0].boardCount).toBe(0);
    expect(groups[0].tasks[0].boardId).toBeNull();
    expect(groups[0].tasks[0].isActive).toBe(false);
  });

  it('a member with both a tombstoned and a live placement resolves to the live board', () => {
    const source = toTask({
      id: 'src',
      title: 'Source',
      currentCount: 10,
      maxCount: null,
      sharedCounterId: null,
      baseline: null,
      isDeleted: false,
      isCounter: true,
    });
    const deadBoard = toBoard({ id: 'board-dead', name: 'Dead', status: BoardStatus.ACTIVE, isDeleted: false });
    const liveBoard = toBoard({ id: 'board-live', name: 'Live', status: BoardStatus.ACTIVE, isDeleted: false });

    const groups = buildSharedCounterGroups({
      tasks: [source],
      boards: [deadBoard, liveBoard],
      boardTasks: [
        { taskId: 'src', boardId: 'board-dead', isDeleted: true },
        { taskId: 'src', boardId: 'board-live' },
      ].map(toBoardTask),
    });

    expect(groups).toHaveLength(1);
    expect(groups[0].tasks[0].boardId).toBe('board-live');
  });
});

describe('buildSharedCounterGroups (fixture-driven, tests/fixtures/sharedCounterGroupsVectors.json)', () => {
  it('fixture is non-empty', () => {
    expect(fixture.vectors.length).toBeGreaterThan(0);
  });

  for (const v of fixture.vectors) {
    it(v.name, () => {
      const groups = buildSharedCounterGroups({
        tasks: v.tasks.map(toTask),
        boards: v.boards.map(toBoard),
        boardTasks: v.boardTasks.map(toBoardTask),
        eventsByTaskId: toVectorEvents(v),
      });

      expect(groups).toHaveLength(v.expected.length);
      groups.forEach((g, i) => {
        const exp = v.expected[i];
        expect(g.counterId).toBe(exp.counterId);
        expect(g.name).toBe(exp.name);
        expect(g.lifetime).toBe(exp.lifetime);
        expect(g.taskCount).toBe(exp.taskCount);
        expect(g.boardCount).toBe(exp.boardCount);
        expect(g.activeTaskCount).toBe(exp.activeTaskCount);
        expect(g.tasks).toHaveLength(exp.tasks.length);
        g.tasks.forEach((m, j) => {
          const expMember = exp.tasks[j];
          expect(m.taskId).toBe(expMember.taskId);
          expect(m.isSource).toBe(expMember.isSource);
          expect(m.boardId).toBe(expMember.boardId);
          expect(m.boardName).toBe(expMember.boardName);
          expect(m.goal).toBe(expMember.goal);
          expect(m.logged).toBe(expMember.logged);
          expect(m.met).toBe(expMember.met);
          expect(m.over).toBe(expMember.over);
          expect(m.isActive).toBe(expMember.isActive);
        });
      });
    });
  }
});
